#!/usr/bin/env python3
"""Generate the Rust/C++ wire protocol constants and record arities.

schema/wire_schema.json is the checked-in, authoritative source.
Use --check in CI so manual edits to either generated language output fail.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema" / "wire_schema.json"
PREFIX = "// Generated by tools/gen_wire_schema.py. Do not edit by hand.\n"
EXPECTED_TAGS = {"ABSENT": 0, "TEXT": 1, "UNSIGNED": 2, "SIGNED": 3}


def render(schema):
    tags = schema["wire_tags"]
    if tags != EXPECTED_TAGS:
        raise ValueError("the stable wire field discriminants cannot change")
    named = schema["named_records"]
    arities = {int(k): v for k, v in schema["record_arities"].items()}
    if sorted(arities) != list(range(1, max(arities) + 1)):
        raise ValueError("record IDs must be dense, positive and start at 1")
    if not all(isinstance(n, int) and not isinstance(n, bool)
               and 1 <= n <= 256 for n in arities.values()):
        raise ValueError("record field counts must be positive integers <= 256")
    if not all(k.startswith("RECORD_") and isinstance(v, int)
               and not isinstance(v, bool) and v in arities or
               k == "RECORD_INCOMPLETE_SNAPSHOT" and v == 0
               for k, v in named.items()):
        raise ValueError("invalid named record IDs")
    if named.get("RECORD_INCOMPLETE_SNAPSHOT") != 0:
        raise ValueError("malformed snapshot event must be reserved record zero")

    rust = (
        PREFIX
        + "mod wire_tags {\n"
        + "".join(f"    pub const {k}: u32 = {v};\n"
                  for k, v in tags.items())
        + "    pub const MAX: u32 = SIGNED;\n}\n\n"
        + "fn expected_wire_field_count(kind: u32) -> Option<usize> {\n"
        + "    match kind {\n"
        + "".join(f"        {k} => Some({arities[k]}),\n"
                  for k in sorted(arities))
        + "        _ => None,\n    }\n}\n"
    )
    cpp = (
        PREFIX
        + "enum : uint32_t {\n"
        + "".join(f"  WIRE_{k} = {v},\n"
                  for k, v in tags.items())
        + "".join(f"  {k} = {v},\n"
                  for k, v in named.items())
        + "};\n"
    )
    return {
        ROOT / "src" / "wire_schema_generated.rs": rust,
        ROOT / "cpp" / "wire_schema_generated.inc": cpp,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail when generated files are out of date")
    args = ap.parse_args()
    try:
        generated = render(json.loads(SCHEMA.read_text(encoding="utf-8")))
    except (ValueError, KeyError, TypeError) as exc:
        print(f"invalid wire schema: {exc}", file=sys.stderr)
        return 1
    stale = []
    for path, expected in generated.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(expected, encoding="utf-8")
    if stale:
        print("wire schema generated sources are stale: "
              + ", ".join(map(str, stale)), file=sys.stderr)
        print("run: python3 tools/gen_wire_schema.py", file=sys.stderr)
        return 1
    print("wire schema generated outputs verified" if args.check
          else "wire schema generated outputs updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
