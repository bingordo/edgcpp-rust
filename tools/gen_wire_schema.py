#!/usr/bin/env python3
"""Generate the Rust/C++ wire protocol constants and record arities.

schema/wire_schema.json is the checked-in, authoritative source.
Use --check in CI so manual edits to either generated language output fail.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "schema" / "wire_schema.json"
PREFIX = "// Generated by tools/gen_wire_schema.py. Do not edit by hand.\n"
EXPECTED_TAGS = {"ABSENT": 0, "TEXT": 1, "UNSIGNED": 2, "SIGNED": 3}



def render_cross_field_relations(schema, arities):
    """Validate and render a conservative cross-field presence rule subset."""
    descriptors = {int(k): values
                   for k, values in schema["record_field_tags"].items()}
    rust_rules, cpp_rules = {}, {}
    for raw_kind, rules in schema.get("record_field_relations", {}).items():
        kind = int(raw_kind)
        if kind not in arities or not isinstance(rules, list) or not rules:
            raise ValueError(f"invalid cross-field rule set for record {kind}")
        rust, cpp = [], []
        for rule in rules:
            name = rule.get("rule")
            if name == "same_presence":
                indices = rule.get("fields")
                if not isinstance(indices, list) or len(indices) != 2:
                    raise ValueError(f"invalid same_presence fields: {rule}")
                required_indices = indices
                controls = []
            elif name == "implies_presence":
                required_indices = [rule.get("when"), rule.get("requires")]
                controls = []
            elif name == "presence_if_eq":
                required_indices = [rule.get("field"), rule.get("value_field")]
                controls = [rule.get("value_field")]
                if not isinstance(rule.get("value"), int) or not (
                    0 <= rule["value"] <= 0xffffffff
                ):
                    raise ValueError(f"invalid conditional field value: {rule}")
            elif name == "presence_if_flag_clear":
                required_indices = [rule.get("field"), rule.get("flags_field")]
                controls = [rule.get("flags_field")]
                if not isinstance(rule.get("mask"), int) or not (
                    1 <= rule["mask"] <= 0xffffffff
                ):
                    raise ValueError(f"invalid conditional flag mask: {rule}")
            else:
                raise ValueError(f"unknown wire cross-field rule: {rule}")
            if any(not isinstance(i, int) or isinstance(i, bool) or
                   i < 0 or i >= arities[kind] for i in required_indices):
                raise ValueError(f"invalid wire cross-field index: {rule}")
            if any(descriptors[kind][i] != "UNSIGNED" for i in controls):
                raise ValueError(f"non-unsigned wire cross-field control: {rule}")
            pres = lambda i, lang: (
                f"(fields[{i}].tag != wire_tags::ABSENT)" if lang == "rust"
                else f"(fields.begin()[{i}].tag != WIRE_ABSENT)"
            )
            value = lambda i, lang: (
                f"fields[{i}].value" if lang == "rust"
                else f"fields.begin()[{i}].value"
            )
            for lang, dest in [("rust", rust), ("cpp", cpp)]:
                if name == "same_presence":
                    a, b = required_indices
                    expression = f"({pres(a, lang)} == {pres(b, lang)})"
                elif name == "implies_presence":
                    a, b = required_indices
                    expression = f"(!{pres(a, lang)} || {pres(b, lang)})"
                elif name == "presence_if_eq":
                    a, b = required_indices
                    expression = (
                        f"({pres(a, lang)} == ({value(b, lang)} == "
                        f"{rule['value']}))"
                    )
                else:
                    a, b = required_indices
                    expression = (
                        f"({pres(a, lang)} == "
                        f"(({value(b, lang)} & {rule['mask']}) == 0))"
                    )
                dest.append(expression)
        rust_rules[kind] = rust
        cpp_rules[kind] = cpp
    return rust_rules, cpp_rules

def render(schema):
    tags = schema["wire_tags"]
    if tags != EXPECTED_TAGS:
        raise ValueError("the stable wire field discriminants cannot change")
    named = schema["named_records"]
    arities = {int(k): v for k, v in schema["record_arities"].items()}
    if sorted(arities) != list(range(1, max(arities) + 1)):
        raise ValueError("record IDs must be dense, positive and start at 1")
    if not all(isinstance(n, int) and not isinstance(n, bool)
               and 1 <= n <= 256 for n in arities.values()):
        raise ValueError("record field counts must be positive integers <= 256")
    if not all(k.startswith("RECORD_") and isinstance(v, int)
               and not isinstance(v, bool) and v in arities or
               k == "RECORD_INCOMPLETE_SNAPSHOT" and v == 0
               for k, v in named.items()):
        raise ValueError("invalid named record IDs")
    if named.get("RECORD_INCOMPLETE_SNAPSHOT") != 0:
        raise ValueError("malformed snapshot event must be reserved record zero")
    # Only well-established wire records are field-typed in the first
    # migration. Untyped records retain the existing decoder validation;
    # each newly typed record must describe all of its fields.
    fields = {}
    for raw_kind, tag_names in schema.get("record_field_tags", {}).items():
        kind = int(raw_kind)
        if kind not in arities or len(tag_names) != arities[kind]:
            raise ValueError(f"typed record {kind} has invalid field count")
        masks = []
        for accepted in tag_names:
            if not isinstance(accepted, str):
                raise ValueError(f"record {kind} has non-string tag descriptor")
            options = accepted.split("|")
            if len(set(options)) != len(options) or any(
                name not in tags for name in options
            ):
                raise ValueError(f"record {kind} has invalid field tag: {accepted}")
            masks.append(sum(1 << tags[name] for name in options))
        fields[kind] = masks
    if set(fields) != set(arities):
        raise ValueError("all wire record kinds must have field tag descriptors")
    rust_relations, cpp_relations = render_cross_field_relations(schema, arities)

    rust = (
        PREFIX
        + "mod wire_tags {\n"
        + "".join(f"    pub const {k}: u32 = {v};\n"
                  for k, v in tags.items())
        + "    pub const MAX: u32 = SIGNED;\n}\n\n"
        + "fn expected_wire_field_count(kind: u32) -> Option<usize> {\n"
        + "    match kind {\n"
        + "".join(f"        {k} => Some({arities[k]}),\n"
                  for k in sorted(arities))
        + "        _ => None,\n    }\n}\n"
        + "\nfn expected_wire_field_tag_masks(kind: u32) -> Option<&'static [u8]> {\n"
        + "    match kind {\n"
        + "".join(
            f"        {kind} => Some(&[{', '.join(str(v) for v in fields[kind])}]),\n"
            for kind in sorted(fields)
        )
        + "        _ => None,\n    }\n}\n"
    )
    rust += (
        "\nfn wire_record_cross_fields_valid(kind: u32, fields: &[WireField]) -> bool {\n"
        + "    match kind {\n"
        + "".join(
            f"        {kind} => fields.len() == {arities[kind]} && (\n"
            + "            " + " &&\n            ".join(rust_relations[kind])
            + "\n        ),\n"
            for kind in sorted(rust_relations)
        )
        + "        _ => true,\n    }\n}\n"
    )
    cpp = (
        PREFIX
        + "enum : uint32_t {\n"
        + "".join(f"  WIRE_{k} = {v},\n"
                  for k, v in tags.items())
        + "".join(f"  {k} = {v},\n"
                  for k, v in named.items())
        + "};\n"
        + "\n// Validate field tags before emitting typed native wire records.\n"
        + "static bool wire_record_field_tags_valid(\n"
        + "    uint32_t kind, std::initializer_list<edgcpp_field> fields)\n"
        + "{\n  switch (kind) {\n"
        + "".join(
            f"  case {kind}: {{\n"
            + f"    const uint8_t masks[] = {{{', '.join(str(v) for v in fields[kind])}}};\n"
            + "    if (fields.size() != sizeof(masks) / sizeof(masks[0])) return false;\n"
            + "    size_t index = 0;\n"
            + "    for (const auto &field : fields) {\n"
            + "      if (field.tag > WIRE_SIGNED ||\n"
            + "          (masks[index++] & (1u << field.tag)) == 0) return false;\n"
            + "    }\n"
            + "    return true;\n  }\n"
            for kind in sorted(fields)
        )
        + "  default: return true;\n  }\n}\n"
    )
    cpp += (
        "\n// Enforce schema-defined relationships between optional fields.\n"
        + "static bool wire_record_cross_fields_valid(\n"
        + "    uint32_t kind, std::initializer_list<edgcpp_field> fields)\n"
        + "{\n  switch (kind) {\n"
        + "".join(
            f"  case {kind}:\n    return fields.size() == {arities[kind]} &&\n"
            + "      " + " &&\n      ".join(cpp_relations[kind]) + ";\n"
            for kind in sorted(cpp_relations)
        )
        + "  default: return true;\n  }\n}\n"
    )
    return {
        ROOT / "src" / "wire_schema_generated.rs": rust,
        ROOT / "cpp" / "wire_schema_generated.inc": cpp,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail when generated files are out of date")
    args = ap.parse_args()
    try:
        generated = render(json.loads(SCHEMA.read_text(encoding="utf-8")))
    except (ValueError, KeyError, TypeError) as exc:
        print(f"invalid wire schema: {exc}", file=sys.stderr)
        return 1
    stale = []
    for path, expected in generated.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(expected, encoding="utf-8")
    if stale:
        print("wire schema generated sources are stale: "
              + ", ".join(map(str, stale)), file=sys.stderr)
        print("run: python3 tools/gen_wire_schema.py", file=sys.stderr)
        return 1
    print("wire schema generated outputs verified" if args.check
          else "wire schema generated outputs updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
